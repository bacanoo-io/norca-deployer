// GenOptions carries values the generator cannot derive from the plan.
type GenOptions struct {
	// GossipKey is the resolved gossip encryption key; empty disables it.
	GossipKey string
	// ReplicationToken is the ACL replication token of a replica region.
	ReplicationToken string
}

// ClusterAddress is the address other nodes use to reach a node.
func ClusterAddress(n *config.NodeConfig) string {
	if n.ClusterAddress != "" {
		return n.ClusterAddress
	}
	return n.Host
}

// retryJoin writes a server_join block. Servers join each other on the Serf
// port; clients join the servers on the RPC port.
func retryJoin(sb *strings.Builder, plan *config.DeploymentPlan, port int, federate bool) {
	sb.WriteString("  server_join {\n")
	sb.WriteString("    retry_join = [\n")
	for i := range plan.Inventory.Masters {
		addr := fmt.Sprintf("%s:%d", ClusterAddress(&plan.Inventory.Masters[i]), port)
		sb.WriteString(fmt.Sprintf("      %q,\n", addr))
	}
	// Servers of other regions (Serf): joining them federates the regions.
	if federate && plan.Federation != nil {
		for _, j := range plan.Federation.Join {
			if !strings.Contains(j, ":") {
				j = fmt.Sprintf("%s:%d", j, port)
			}
			sb.WriteString(fmt.Sprintf("      %q,\n", j))
		}
	}
	sb.WriteString("    ]\n")
	sb.WriteString("  }\n")
}

// GenerateNorcaConfig produces the final norca.hcl configuration for a specific node.
func GenerateNorcaConfig(node *config.NodeConfig, plan *config.DeploymentPlan, paths *storage.ResolvedPaths, isMaster bool, opts GenOptions) string {
	var sb strings.Builder

	// Header and base attributes
	sb.WriteString("# Norca Agent Configuration - Generated by norca-deployer\n\n")
	sb.WriteString(fmt.Sprintf("datacenter = %q\n", plan.NodeDatacenter(node)))
	sb.WriteString(fmt.Sprintf("region     = %q\n", plan.Metadata.Region))
	sb.WriteString(fmt.Sprintf("name       = %q\n", node.Hostname))
	sb.WriteString(fmt.Sprintf("data_dir   = %q\n", paths.DataDir))
	if plan.Network.BindAddress != "" {
		sb.WriteString(fmt.Sprintf("bind_addr  = %q\n", plan.Network.BindAddress))
	}

	logLevel := "INFO"
	if node.ServerSettings != nil && node.ServerSettings.LogLevel != "" {
		logLevel = node.ServerSettings.LogLevel
	}
	sb.WriteString(fmt.Sprintf("log_level  = %q\n", logLevel))
	if plan.Tuning.SetupLogrotate && paths.LogDir != "" {
		// The agent rotates its own log file; no external logrotate needed.
		sb.WriteString(fmt.Sprintf("log_file   = %q\n", joinPath(paths, paths.LogDir, "norca.log")))
		sb.WriteString("log_rotate_bytes     = 104857600\n")
		sb.WriteString("log_rotate_max_files = 10\n")
	}
	sb.WriteString("\n")

	// Ports
	sb.WriteString("ports {\n")
	sb.WriteString(fmt.Sprintf("  http = %d\n", plan.Network.Ports.HTTP))
	sb.WriteString(fmt.Sprintf("  rpc  = %d\n", plan.Network.Ports.RPC))
	sb.WriteString(fmt.Sprintf("  serf = %d\n", plan.Network.Ports.Serf))
	sb.WriteString("}\n\n")

	// Without bind_address the agent listens on its cluster address only;
	// HTTP also on loopback, which the local CLI (and the deployer) uses.
	advHost := ClusterAddress(node)
	if plan.Network.BindAddress == "" {
		addr := discovery.ResolveNodeAddress(&plan.Network, advHost)
		sb.WriteString("addresses {\n")
		sb.WriteString(fmt.Sprintf("  http = %q\n", "127.0.0.1 "+addr))
		sb.WriteString(fmt.Sprintf("  rpc  = %q\n", addr))
		sb.WriteString(fmt.Sprintf("  serf = %q\n", addr))
		sb.WriteString("}\n\n")
	}

	// Dynamic Advertise addresses (supports exact name, prefix, suffix matching or fallback IP)
	httpAdv := discovery.ResolveAdvertiseAddress(&plan.Network, advHost, plan.Network.Ports.HTTP)
	rpcAdv := discovery.ResolveAdvertiseAddress(&plan.Network, advHost, plan.Network.Ports.RPC)
	serfAdv := discovery.ResolveAdvertiseAddress(&plan.Network, advHost, plan.Network.Ports.Serf)

	sb.WriteString("advertise {\n")
	sb.WriteString(fmt.Sprintf("  http = %q\n", httpAdv))
	sb.WriteString(fmt.Sprintf("  rpc  = %q\n", rpcAdv))
	sb.WriteString(fmt.Sprintf("  serf = %q\n", serfAdv))
	sb.WriteString("}\n\n")

	// TLS configuration
	if plan.Security.TLSEnabled {
		certFile := joinPath(paths, paths.TLSDir, "server.pem")
		keyFile := joinPath(paths, paths.TLSDir, "server-key.pem")
		if !isMaster {
			certFile = joinPath(paths, paths.TLSDir, "client.pem")
			keyFile = joinPath(paths, paths.TLSDir, "client-key.pem")
		}

		sb.WriteString("tls {\n")
		sb.WriteString("  http = true\n")
		sb.WriteString("  rpc  = true\n\n")
		sb.WriteString(fmt.Sprintf("  ca_file   = %q\n", joinPath(paths, paths.TLSDir, "ca.pem")))
		sb.WriteString(fmt.Sprintf("  cert_file = %q\n", certFile))
		sb.WriteString(fmt.Sprintf("  key_file  = %q\n\n", keyFile))
		sb.WriteString(fmt.Sprintf("  verify_server_hostname = %t\n", plan.Security.VerifyServerHostname))
		sb.WriteString(fmt.Sprintf("  verify_https_client    = %t\n", plan.Security.VerifyHTTPSClient))
		sb.WriteString("}\n\n")
	}

	// ACL configuration
	if plan.Security.ACL != nil && plan.Security.ACL.Enabled {
		sb.WriteString("acl {\n")
		sb.WriteString("  enabled = true\n")
		if isMaster && opts.ReplicationToken != "" {
			sb.WriteString(fmt.Sprintf("  replication_token = %q\n", opts.ReplicationToken))
		}
		sb.WriteString("}\n\n")
	}

	// Server block
	if isMaster {
		sb.WriteString("server {\n")
		sb.WriteString("  enabled          = true\n")
		sb.WriteString(fmt.Sprintf("  bootstrap_expect = %d\n", node.ServerSettings.BootstrapExpect))
		if node.ServerSettings.RaftMultiplier > 1 {
			sb.WriteString(fmt.Sprintf("  raft_multiplier  = %d\n", node.ServerSettings.RaftMultiplier))
		}
		if opts.GossipKey != "" {
			sb.WriteString(fmt.Sprintf("  encrypt          = %q\n", opts.GossipKey))
		}
		if plan.Federation != nil {
			sb.WriteString(fmt.Sprintf("  authoritative_region = %q\n", plan.Federation.AuthoritativeRegion))
		}

		// Server join list (Serf)
		sb.WriteString("\n")
		retryJoin(&sb, plan, plan.Network.Ports.Serf, true)

		// Embedded Backup configuration
		if plan.Backup != nil && plan.Backup.Enabled {
			writeBackup(&sb, plan.Backup)
		}
		writeExtraHCL(&sb, node.ServerSettings.ExtraHCL)

		sb.WriteString("}\n\n")
	}

	// Client block
	if !isMaster || (node.ClientSettings != nil) {
		cs := node.ClientSettings
		if cs == nil {
			cs = &config.ClientSettings{}
		}
		sb.WriteString("client {\n")
		sb.WriteString("  enabled = true\n")

		// CNI paths
		sb.WriteString(fmt.Sprintf("  cni_path       = %q\n", paths.CNIBinDir))
		sb.WriteString(fmt.Sprintf("  cni_config_dir = %q\n", paths.CNIConfigDir))
		if cs.NetworkInterface != "" {
			sb.WriteString(fmt.Sprintf("  network_interface = %q\n", cs.NetworkInterface))
		}
		if cs.GCDiskUsageThreshold > 0 {
			sb.WriteString(fmt.Sprintf("  gc_disk_usage_threshold = %d\n", cs.GCDiskUsageThreshold))
		}
		if cs.NodeClass != "" {
			sb.WriteString(fmt.Sprintf("  node_class = %q\n", cs.NodeClass))
		}
		if cs.NodePool != "" {
			sb.WriteString(fmt.Sprintf("  node_pool  = %q\n", cs.NodePool))
		}
		// A custom range of dynamic ports; the firewall opens the same
		// range. Without it the agent's default (20000-32000) applies.
		if plan.Network.DynamicPorts != nil {
			minPort, maxPort := plan.DynamicPortRange()
			sb.WriteString(fmt.Sprintf("  min_dynamic_port = %d\n", minPort))
			sb.WriteString(fmt.Sprintf("  max_dynamic_port = %d\n", maxPort))
		}
		sb.WriteString("\n")

		// Server join addresses (RPC)
		retryJoin(&sb, plan, plan.Network.Ports.RPC, false)
		writeClientLabels(&sb, cs)

		// Only the listed drivers are fingerprinted.
		if drivers := clientDrivers(cs); len(drivers) > 0 {
			sb.WriteString("\n  options = {\n")
			sb.WriteString(fmt.Sprintf("    \"driver.allowlist\" = %q\n", strings.Join(drivers, ",")))
			sb.WriteString("  }\n")
		}

		// Host volumes including native application directories
		sb.WriteString(paths.GenerateHostVolumeBlocks(node.ClientSettings))
		writeExtraHCL(&sb, cs.ExtraHCL)

		sb.WriteString("}\n")

		// raw_exec is disabled unless enabled explicitly in its plugin block.
		if cs.EnableRawExec {
			sb.WriteString("\nplugin \"raw_exec\" {\n")
			sb.WriteString("  config {\n")
			sb.WriteString("    enabled = true\n")
			sb.WriteString("  }\n")
			sb.WriteString("}\n")
		}
	}

	return sb.String()
}

// clientDrivers returns the driver allowlist. raw_exec is only listed when it
// is enabled.
func clientDrivers(cs *config.ClientSettings) []string {
	var res []string
	for _, d := range cs.Drivers {
		if d == "raw_exec" && !cs.EnableRawExec {
			continue
		}
		res = append(res, d)
	}
	if cs.EnableRawExec && !containsString(res, "raw_exec") {
		res = append(res, "raw_exec")
	}
	return res
}

func containsString(list []string, s string) bool {
	for _, v := range list {
		if v == s {
			return true
		}
	}
	return false
}

func writeBackup(sb *strings.Builder, b *config.BackupConfig) {
	sb.WriteString("\n  backup {\n")
	sb.WriteString("    enabled  = true\n")
	sb.WriteString(fmt.Sprintf("    schedule = %q\n\n", b.Schedule))
	sb.WriteString(fmt.Sprintf("    destination %q {\n", b.Destination.Name))
	sb.WriteString(fmt.Sprintf("      type             = %q\n", b.Destination.Type))
	if b.Destination.Path != "" {
		sb.WriteString(fmt.Sprintf("      path             = %q\n", b.Destination.Path))
	}
	if b.Destination.Endpoint != "" {
		sb.WriteString(fmt.Sprintf("      endpoint         = %q\n", b.Destination.Endpoint))
	}
	if b.Destination.Bucket != "" {
		sb.WriteString(fmt.Sprintf("      bucket           = %q\n", b.Destination.Bucket))
	}
	if b.Destination.Prefix != "" {
		sb.WriteString(fmt.Sprintf("      prefix           = %q\n", b.Destination.Prefix))
	}
	if b.Destination.Type != "directory" {
		sb.WriteString(fmt.Sprintf("      force_path_style = %t\n", b.Destination.ForcePathStyle))
	}
	sb.WriteString("    }\n")

	// Norca encrypts every backup with age and refuses a backup block
	// without recipients.
	sb.WriteString("\n    encryption {\n")
	sb.WriteString("      recipients = [\n")
	for _, r := range b.Encryption.Recipients {
		sb.WriteString(fmt.Sprintf("        %q,\n", r))
	}
	sb.WriteString("      ]\n")
	sb.WriteString("    }\n")

	if rt := b.Retention; rt != nil {
		sb.WriteString("\n    retention {\n")
		for _, kv := range []struct {
			key string
			val int
		}{
			{"keep_hourly", rt.KeepHourly},
			{"keep_daily", rt.KeepDaily},
			{"keep_weekly", rt.KeepWeekly},
			{"keep_monthly", rt.KeepMonthly},
		} {
			if kv.val > 0 {
				sb.WriteString(fmt.Sprintf("      %-12s = %d\n", kv.key, kv.val))
			}
		}
		sb.WriteString("    }\n")
	}
	sb.WriteString("  }\n")
}

// writeClientLabels writes the meta, host_network, reserved and
// drain_on_shutdown blocks of a client. Meta keys are sorted so that the
// configuration (and its digest) is stable.
func writeClientLabels(sb *strings.Builder, cs *config.ClientSettings) {
	if len(cs.Meta) > 0 {
		keys := make([]string, 0, len(cs.Meta))
		for k := range cs.Meta {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		sb.WriteString("\n  meta {\n")
		for _, k := range keys {
			sb.WriteString(fmt.Sprintf("    %q = %q\n", k, cs.Meta[k]))
		}
		sb.WriteString("  }\n")
	}
	for _, hn := range cs.HostNetworks {
		sb.WriteString(fmt.Sprintf("\n  host_network %q {\n", hn.Name))
		if hn.Interface != "" {
			sb.WriteString(fmt.Sprintf("    interface = %q\n", hn.Interface))
		}
		if hn.CIDR != "" {
			sb.WriteString(fmt.Sprintf("    cidr = %q\n", hn.CIDR))
		}
		if hn.ReservedPorts != "" {
			sb.WriteString(fmt.Sprintf("    reserved_ports = %q\n", hn.ReservedPorts))
		}
		sb.WriteString("  }\n")
	}
	if r := cs.Reserved; r != nil {
		sb.WriteString("\n  reserved {\n")
		if r.CPU > 0 {
			sb.WriteString(fmt.Sprintf("    cpu = %d\n", r.CPU))
		}
		if r.Memory > 0 {
			sb.WriteString(fmt.Sprintf("    memory = %d\n", r.Memory))
		}
		if r.Disk > 0 {
			sb.WriteString(fmt.Sprintf("    disk = %d\n", r.Disk))
		}
		if r.ReservedPorts != "" {
			sb.WriteString(fmt.Sprintf("    reserved_ports = %q\n", r.ReservedPorts))
		}
		sb.WriteString("  }\n")
	}
	if d := cs.DrainOnShutdown; d != nil {
		deadline := d.Deadline
		if deadline == "" {
			deadline = "1h"
		}
		sb.WriteString("\n  drain_on_shutdown {\n")
		sb.WriteString(fmt.Sprintf("    deadline           = %q\n", deadline))
		sb.WriteString(fmt.Sprintf("    force              = %t\n", d.Force))
		sb.WriteString(fmt.Sprintf("    ignore_system_jobs = %t\n", d.IgnoreSystemJobs))
		sb.WriteString("  }\n")
	}
}

// writeExtraHCL appends the operator's own settings inside a block.
func writeExtraHCL(sb *strings.Builder, extra string) {
	extra = strings.TrimSpace(extra)
	if extra == "" {
		return
	}
	sb.WriteString("\n  # extra_hcl from the plan\n")
	for _, line := range strings.Split(extra, "\n") {
		sb.WriteString("  " + line + "\n")
	}
}
